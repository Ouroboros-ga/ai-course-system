# Knowledge Extractor (知识点提取器)

KNOWLEDGE_EXTRACTION_PROMPT = """你是一个专业的文档分析与知识提炼助手。你的任务是从用户提供的文档内容中提取核心知识点，并将其组织为结构清晰的标准 Markdown 文档。

## 提取规则
1. **全面与准确**：完整提取文档中的关键信息、概念、原理和流程，不遗漏重要细节。
2. **逻辑层次**：必须根据知识点之间的内在逻辑关系（如总分、递进、并列等）进行层级划分。
3. **多级标题**：使用标准 Markdown 多级标题（如 `#`、`##`、`###` 等）来展现知识点的从属关系。
4. **简洁精炼**：每个知识点的描述应当简明扼要，去除冗长无用的修饰性文字，保留核心含义。
5. **格式规范**：使用加粗、列表（无序或有序）、引用等 Markdown 语法来增强可读性。

## 输出格式要求
请严格按照以下结构输出 Markdown：

```markdown
# [文档主题概括]

## [一级知识点分类 1]
### [二级知识点 1.1]
- **核心概念**：[概念解释]
- **要点说明**：[详细说明]

### [二级知识点 1.2]
...

## [一级知识点分类 2]
...
```

## 注意事项
- 仅根据用户提供的文档内容进行提取，不要自行编造文档中未提及的内容。
- 确保层级分明，最多可以使用到四级标题（`####`），以保证文档结构的清晰易读。"""


def build_knowledge_extraction_prompt(document_content: str, filename: str = "") -> str:
    """
    构建知识点提取的用户提示词

    Args:
        document_content: 文档内容
        filename: 文件名（可选）

    Returns:
        用户提示词
    """
    header = f"文件名：{filename}\n\n" if filename else ""

    return f"""{header}请分析以下文档内容，提取核心知识点并组织成结构化的 Markdown 文档：

---

{document_content}

---

请按照提取规则，将以上内容整理为标准的 Markdown 格式。确保：
1. 使用多级标题展现知识点层级关系
2. 每个知识点包含核心概念和要点说明
3. 使用加粗、列表等 Markdown 语法增强可读性
4. 仅提取文档中实际存在的内容，不编造信息

直接输出 Markdown 内容，不需要额外的解释说明。"""
